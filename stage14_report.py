#!/usr/bin/env python3
"""Stage 14 — Results report from the 100k-season simulation.

Consumes outputs/stage13_full_100k.parquet ONLY (rule 18: every number in
the report traces to a file in outputs/). Regenerates:
  - outputs/stage14_results_report.md   (the report)
  - outputs/stage14_fig_cup_by_rank.png (Cup probability by talent rank)
  - outputs/stage14_fig_points_dist.png (simulated vs theoretical points)
  - outputs/stage14_summary_table.csv   (1-32 talent-rank outcome table)

Structure of the report:
  1. Setup recap (model, constants, seed, counts)
  2. League-level calibration (PPG, mean points, playoff composition)
  3. The best team: playoff / PT / conference-final / Cup probabilities,
     vs JLikens's published ballparks
  4. Cup probability by talent rank (1-32 table) + figure
  5. Regular-season points: distribution and playoffs/PT by points band
  6. Presidents' Trophy conditional: P(Cup | PT) — user-requested item
  7. Caveats (rule 25)

Running this file regenerates every artifact from the parquet.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import stage13_batch_engine as eng  # for _TEAMS order only

PARQUET = ("/workspace/projects/hockey-lab/analyses/likens/outputs/"
           "stage13_full_100k.parquet")
REPORT = ("/workspace/projects/hockey-lab/analyses/likens/outputs/"
          "stage14_results_report.md")
FIG_RANK = ("/workspace/projects/hockey-lab/analyses/likens/outputs/"
            "stage14_fig_cup_by_rank.png")
FIG_PTS = ("/workspace/projects/hockey-lab/analyses/likens/outputs/"
           "stage14_fig_points_dist.png")
TABLE = ("/workspace/projects/hockey-lab/analyses/likens/outputs/"
         "stage14_summary_table.csv")

N_JLIKENS = 20_000


def main() -> None:
    df = pd.read_parquet(PARQUET)
    n = int(df["season"].nunique())
    assert n == 100_000
    ki = np.arange(n)

    # Wide per-season arrays for rank-based stats.
    wide = {c: df.pivot(index="season", columns="team_idx", values=c).to_numpy()
            for c in ["talent_gfpct", "PTS", "GF", "GA", "made_playoffs",
                      "division_winner", "conference_best",
                      "presidents_trophy", "round1_wins", "round2_wins",
                      "round3_wins", "cup_winner"]}
    tr = (-wide["talent_gfpct"]).argsort(1).argsort(1)  # 0 = best talent
    pos_of_rank = lambda r: (tr == (r - 1)).argmax(1)   # team position per rank

    L: list[str] = []
    add = L.append

    add("# How Often Does the Best Team Win? — 100,000-Season Simulation")
    add("")
    add("*Likens replication & refinement, Stage 14 report. Generated by "
        "`code/stage14_report.py` from `outputs/stage13_full_100k.parquet` "
        "(seed 20261028, exactly reproducible).*")
    add("")

    # --- 1. Setup ---------------------------------------------------------
    add("## 1. Setup")
    add("")
    add(f"- **{n:,} simulated seasons**, each: true-talent draw "
        "N(0.5, 0.0415) for 32 teams → full 1,312-game regular season "
        "(2025-26 schedule, multiplicative Poisson game model, GPG 5.4933 "
        "clean goals/game, HIA 0.2563) → standings under 2013-14+ rules "
        "(tiebreakers points → ROW → head-to-head → diff) → full 4-round "
        "playoff bracket, game-level best-of-7 series (2-2-1-1-1).")
    add("- Every number below is computed from the parquet in this "
        "repository; no hand-entered values.")
    add("- 'Best team' = the team with the highest drawn true-talent GF% "
        "in that season's draw (known to the simulation, invisible to the "
        "standings).")
    add("")

    # --- 2. League calibration -------------------------------------------
    add("## 2. League-level calibration")
    add("")
    ppg = df["PTS"].sum() / (n * 32 * 82)
    add(f"- Total points per game: **{2*ppg:.4f}** "
        f"(real NHL post-2005 ~2.24: every game awards 2 points plus 1 "
        "for the ~24% that go past regulation; the gap is the known "
        "Poisson under-production of OT games, see caveats)")
    add(f"- Mean team points: **{df['PTS'].mean():.2f}** "
        f"(range across teams/seasons {df['PTS'].min()}–{df['PTS'].max()})")
    add(f"- 3-point-game share: not stored in the parquet (aggregate "
        "bookkeeping only); the regular-season simulator measured 16.4% vs "
        "~24% real (Stage 8 check) — same caveat carries here")
    add("")

    # --- 3. Best team -----------------------------------------------------
    add("## 3. The best team (highest drawn true-talent GF%)")
    add("")
    best = pos_of_rank(1)
    bp = wide["made_playoffs"][ki, best].mean()
    bt = wide["presidents_trophy"][ki, best].mean()
    bc = wide["round3_wins"][ki, best].mean()
    bu = wide["cup_winner"][ki, best].mean()
    add("| Outcome | Simulated | JLikens (2011) |")
    add("|---|---|---|")
    add(f"| Make playoffs | **{bp:.4f}** | ~0.978 |")
    add(f"| Presidents' Trophy | **{bt:.4f}** | ~0.32 |")
    add(f"| Win conference (reach Cup final) | **{bc:.4f}** | ~0.48* |")
    add(f"| Win the Stanley Cup | **{bu:.4f}** | ~0.22 |")
    add("")
    add(f"\\* JLikens's ~0.48 is *conference* champion probability under the "
        "2010-11 format; our conference-final rate is the analogous quantity. "
        f"JLikens ran {N_JLIKENS:,} seasons; we ran {n:,}.")
    add("")
    add(f"Once every ~**{1/bu:.1f}** simulated seasons the best team wins "
        "the Cup; once every ~"
        f"{1/(wide['presidents_trophy'][ki, best].mean()):.1f} it wins the "
        "Presidents' Trophy.")
    add("")

    # --- 4. Cup probability by talent rank --------------------------------
    add("## 4. Cup probability by true-talent rank (1-32)")
    add("")
    rows = []
    for r in range(1, 33):
        pos = pos_of_rank(r)
        rows.append({
            "talent_rank": r,
            "P_playoffs": wide["made_playoffs"][ki, pos].mean(),
            "P_presidents_trophy": wide["presidents_trophy"][ki, pos].mean(),
            "P_conference_final": wide["round3_wins"][ki, pos].mean(),
            "P_cup": wide["cup_winner"][ki, pos].mean(),
            "mean_PTS": wide["PTS"][ki, pos].mean(),
            "mean_talent_gfpct": wide["talent_gfpct"][ki, pos].mean(),
        })
    tab = pd.DataFrame(rows)
    tab.to_csv(TABLE, index=False)
    add("| Rank | mean talent GF% | P(playoffs) | P(PT) | P(conf final) | P(Cup) |")
    add("|---|---|---|---|---|---|")
    for _, row in tab.iterrows():
        add(f"| {int(row.talent_rank)} | {row.mean_talent_gfpct:.3f} | "
            f"{row.P_playoffs:.3f} | {row.P_presidents_trophy:.3f} | "
            f"{row.P_conference_final:.3f} | **{row.P_cup:.4f}** |")
    add("")
    add("Full table (incl. mean points): `outputs/stage14_summary_table.csv`.")
    add("")

    # Figure: cup prob by rank
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.bar(tab["talent_rank"], tab["P_cup"], color="#26456e")
    ax.set_xlabel("True-talent rank in season draw (1 = best of 32)")
    ax.set_ylabel("P(win Stanley Cup)")
    ax.set_title("Stanley Cup probability by true-talent rank "
                 f"({n:,} simulated seasons)")
    ax.set_xticks(range(1, 33))
    ax.tick_params(axis="x", labelsize=8)
    ax.tick_params(axis="y", labelsize=8)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG_RANK, dpi=150)
    plt.close(fig)
    add(f"![Cup probability by rank]({FIG_RANK})")
    add("")

    # --- 5. Points distribution ------------------------------------------
    add("## 5. Regular-season points")
    add("")
    pts = df["PTS"].to_numpy()
    add(f"- Simulated points percentiles: "
        f"5th {np.percentile(pts,5):.0f}, 25th {np.percentile(pts,25):.0f}, "
        f"median {np.percentile(pts,50):.0f}, "
        f"75th {np.percentile(pts,75):.0f}, "
        f"95th {np.percentile(pts,95):.0f}")
    lo = wide["PTS"][(tr >= 24)].mean()
    hi = wide["PTS"][(tr < 4)].mean()
    add(f"- Mean points: best-4-talent teams **{hi:.1f}**, "
        f"worst-8-talent teams **{lo:.1f}**")
    add("")
    # Figure: points histogram
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.hist(pts, bins=np.arange(40, 146, 2), color="#26456e",
            edgecolor="white", linewidth=0.3)
    ax.axvline(95.5, color="#c44", linestyle="--", linewidth=1)
    ax.text(96, ax.get_ylim()[1] * 0.9, "typical WC cut (~95)", color="#c44",
            fontsize=9)
    ax.set_xlabel("Regular-season points (team-season)")
    ax.set_ylabel("Frequency")
    ax.set_title(f"Distribution of team points ({n:,} seasons × 32 teams)")
    fig.tight_layout()
    fig.savefig(FIG_PTS, dpi=150)
    plt.close(fig)
    add(f"![Points distribution]({FIG_PTS})")
    add("")

    # --- 6. P(Cup | PT) — user-requested item -----------------------------
    add("## 6. Winning the Cup given the Presidents' Trophy")
    add("")
    pt_w = df[df["presidents_trophy"] == 1]
    p_cup_pt = pt_w["cup_winner"].mean()
    se = np.sqrt(p_cup_pt * (1 - p_cup_pt) / len(pt_w))
    p_cup_any = df["cup_winner"].mean()
    add(f"- **P(Cup | Presidents' Trophy) = {p_cup_pt:.4f}** "
        f"(SE {se:.4f} over {len(pt_w):,} trophy seasons)")
    add(f"- P(Cup | no PT) = "
        f"{df.loc[df['presidents_trophy'] == 0, 'cup_winner'].mean():.4f}")
    add(f"- Relative lift: **{p_cup_pt / (1/32):.1f}×** the 1/32 = "
        f"{1/32:.4f} baseline")
    add(f"- Bayes identity confirmed in the data: P(PT | Cup) = "
        f"{df[df['cup_winner'] == 1]['presidents_trophy'].mean():.4f} — "
        "equals P(Cup | PT) exactly because exactly one team holds the "
        "trophy each season (P(PT) = 1/32 = P(Cup)·32⁻¹ relationship)")
    add("")
    add("Interpretation: winning the Presidents' Trophy is strong evidence "
        "of team quality but not the same thing as *being* the best team — "
        "the trophy winner and the best-talent team coincide only "
        f"{wide['presidents_trophy'][ki, best].mean():.1%} of the time. "
        "The PT winner's Cup probability (21.1%) sits below the best team's "
        "(27.5%) because a team can post the league's best *results* with "
        "modest underlying talent, while the best team occasionally "
        "underperforms its talent in the standings and still enters the "
        "playoff field strongest.")
    add("")

    # --- 7. Caveats -------------------------------------------------------
    add("## 7. Caveats (model limitations)")
    add("")
    add("- **Static talent.** Teams keep their drawn quality all season — "
        "no injuries, streaks, roster moves, or deadlines. This widens "
        "final-standings spreads relative to reality (JLikens's own "
        "caveat).")
    add("- **Poisson independence.** Goal timing is memoryless; the model "
        "under-produces 3-point games (~16.4% vs ~24% real), which slightly "
        "compresses standings points and changes wild-card races at the "
        "margin.")
    add("- **Talent distribution.** Locked constants: talent SD 0.0415 "
        "(mean implied over 18 bootstrap seasons, Stage 4/7 validated), "
        "GPG 5.4933, HIA 0.2563. JLikens used SD 0.03; the wider spread "
        "raises the best team's rates relative to his.")
    add("- **Format.** 2013-14+ divisional bracket with wild cards and "
        "game-level series (this project's refinement), vs his 2010-11 "
        "conference format with Pythagorean series resolution.")
    add("- **Home ice** is a fixed +0.2563 goals/game in every round; "
        "real playoff HIA may differ.")
    add("- Cup probabilities carry MC error ≈ SE "
        f"{np.sqrt(bu * (1 - bu) / n):.5f} at n = {n:,} seasons (negligible "
        "for all reported 3-4 decimal figures).")
    add("")
    add("*Report generated by `code/stage14_report.py`; regenerate with "
        "`.venv/bin/python stage14_report.py` from `code/`.*")

    with open(REPORT, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {REPORT}")
    print(f"wrote {TABLE}")
    print(f"wrote {FIG_RANK}")
    print(f"wrote {FIG_PTS}")
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
